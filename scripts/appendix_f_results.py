"""Generate Appendix F - the full result tables - from the model's own outputs.

Reads `outputs/data/energy/dispatch_results.json` plus the four report files and
writes the complete result set that Chapter 5 quotes from but cannot table.

Generated rather than typed, so the appendix cannot drift from the solve. Every
number here is read from an artefact; nothing is re-derived by hand.

Run from the repo root:
    python scripts/appendix_f_results.py
"""
from __future__ import annotations

import json
import os
from datetime import datetime, timezone

ENERGY = os.path.join("outputs", "data", "energy")
OUT = os.path.join("..", "..", "WRITEUP", "APPENDIX", "F_results.md")

PERIODS = ["2030", "2042", "2055"]

# Ladder of named scenarios, in the order they add capability.
LADDER = [
    ("bau", "Business as usual"),
    ("pv_only", "Rooftop and ground-mount PV only"),
    ("pv_battery", "PV plus battery"),
    ("pv_battery_v2g", "PV, battery and vehicle-to-grid"),
    ("pv_battery_v2g_biomass", "PV, battery, V2G and biomass"),
    ("full_stack", "Full design package"),
]

TECHS = [
    ("rooftop_pv_kwp", "Rooftop PV", "kWp"),
    ("solar_farm_kwp", "Solar farm", "kWp"),
    ("carport_kwp", "Solar carports", "kWp"),
    ("floating_pv_kwp", "Canal-top and floating PV", "kWp"),
    ("bipv_kwp", "Building-integrated PV", "kWp"),
    ("solar_thermal_m2", "Solar thermal collectors", "m2"),
    ("battery_kwh", "Battery storage", "kWh"),
    ("thermal_storage_kwh", "Thermal storage", "kWh"),
    ("v2g_units", "Vehicle-to-grid units", "units"),
    ("biomass_kw_e", "Biomass CHP", "kW_e"),
    ("wte_kw_e", "Waste to energy", "kW_e"),
    ("biogas_kw_e", "Biogas", "kW_e"),
]


def load(name):
    path = os.path.join(ENERGY, name)
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def n(v, dp=1):
    if v is None:
        return "-"
    if isinstance(v, (int, float)) and abs(v) < 5e-9:
        v = 0.0  # solver noise prints as -0.0 otherwise
    return f"{v:,.{dp}f}"


def gwh(v):
    return "-" if v is None else f"{v / 1e6:,.2f}"


def cr(v):
    """Indian crore, the unit the project reports money in."""
    return "-" if v is None else f"{v / 1e7:,.2f}"


def main() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    os.chdir(root)

    d = load("dispatch_results.json")
    if d is None:
        raise SystemExit("dispatch_results.json not found - run the regen first")
    scen = {}
    alphas = []
    for s in d["scenarios"]:
        if s["name"] == "full_stack" and s.get("alpha", 0.0) not in (0.0, None):
            alphas.append(s)
            continue
        scen.setdefault(s["name"], s)
    # the alpha=0 full_stack is production; later duplicates are the sweep
    fs_runs = [s for s in d["scenarios"] if s["name"] == "full_stack"]
    prod = fs_runs[0]
    sweep = sorted(
        {round(s.get("alpha", 0.0), 4): s for s in fs_runs}.items(), key=lambda kv: kv[0]
    )
    bau = scen["bau"]

    equity = load("equity_report.json")
    boundary = load("boundary_flows_ledger.json")
    techfin = load("tech_finance_report.json")

    P = []
    A = P.append

    A("# Appendix F - Full results\n")
    A(
        "**Generated by `scripts/appendix_f_results.py`** from "
        "`outputs/data/energy/dispatch_results.json` and the report files beside it. "
        "Every figure is read from a model artefact; none is re-derived by hand. "
        "Rebuild after any re-pin so the appendix cannot drift from the solve.\n"
    )
    A(
        f"Solve: {d.get('slices_per_year')} representative slices per year, "
        f"three investment periods, results schema v{d.get('version')}. "
        f"Table generated {datetime.now(timezone.utc):%Y-%m-%d}.\n"
    )

    # ---------------------------------------------------------------- F.1
    A("\n---\n\n## F.1 Headline, town against business as usual\n")
    A("| quantity | town | business as usual | difference |")
    A("|---|---|---|---|")
    rows = [
        ("Annual system cost (INR)", prod["annual_cost_inr"], bau["annual_cost_inr"], 0),
        ("Annual emissions (kgCO2)", prod["annual_emissions_kgco2"], bau["annual_emissions_kgco2"], 0),
        ("Lifetime cost (INR)", prod["lifetime_cost_inr"], bau["lifetime_cost_inr"], 0),
        ("Annual demand (kWh)", prod["annual_demand_kwh"], bau["annual_demand_kwh"], 0),
        ("Grid import (kWh)", prod["grid_import_kwh"], bau["grid_import_kwh"], 0),
        ("Grid export (kWh)", prod["grid_export_kwh"], bau["grid_export_kwh"], 0),
        ("Grid connection (MW)", prod.get("grid_connection_mw"), bau.get("grid_connection_mw"), 2),
        ("Levelised cost (INR/kWh)", prod.get("lcoe_inr_per_kwh"), bau.get("lcoe_inr_per_kwh"), 4),
    ]
    for label, t, b, dp in rows:
        if t is None or b is None:
            A(f"| {label} | {n(t, dp)} | {n(b, dp)} | - |")
            continue
        pct = (t - b) / b * 100 if b else 0
        A(f"| {label} | {n(t, dp)} | {n(b, dp)} | {pct:+.2f} % |")

    cs = (1 - prod["annual_cost_inr"] / bau["annual_cost_inr"]) * 100
    es = (1 - prod["annual_emissions_kgco2"] / bau["annual_emissions_kgco2"]) * 100
    A(
        f"\n**Cost saving {cs:.4f} %. Emissions saving {es:.4f} %.** "
        "The counterfactual holds the same building programme on the same site, so "
        "the comparison isolates the energy design rather than the plan.\n"
    )
    A(
        f"Renewable share {prod.get('renewable_share', 0) * 100:.1f} % "
        f"(self-generated, including biomass, waste-to-energy and biogas). "
        f"PV self-consumption share {prod.get('pv_self_consumption_share', 0) * 100:.1f} %.\n"
    )

    # ---------------------------------------------------------------- F.2
    A("\n---\n\n## F.2 Scenario ladder\n")
    A("Each row adds capability to the row above it, on the same layout and demand.\n")
    A("| scenario | | annual cost (INR) | vs BAU | annual CO2 (kg) | vs BAU |")
    A("|---|---|---|---|---|---|")
    for key, label in LADDER:
        s = scen.get(key)
        if not s:
            continue
        c = (1 - s["annual_cost_inr"] / bau["annual_cost_inr"]) * 100
        e = (1 - s["annual_emissions_kgco2"] / bau["annual_emissions_kgco2"]) * 100
        A(
            f"| `{key}` | {label} | {n(s['annual_cost_inr'], 0)} | {c:+.2f} % | "
            f"{n(s['annual_emissions_kgco2'], 0)} | {e:+.2f} % |"
        )

    # ---------------------------------------------------------------- F.3
    A("\n---\n\n## F.3 Build path\n")
    pb = prod.get("period_breakdown", {})
    A("### F.3.1 New capacity built in each period\n")
    A("| technology | units | 2030 | 2042 | 2055 |")
    A("|---|---|---|---|---|")
    keymap = {"solar_farm_kwp": ("farm_fixed_kwp", "farm_tracked_kwp")}
    for key, label, unit in TECHS:
        vals = []
        for p in PERIODS:
            nb = pb.get(p, {}).get("new_build", {})
            if key in keymap:
                vals.append(sum(nb.get(k, 0.0) or 0.0 for k in keymap[key]))
            else:
                vals.append(nb.get(key))
        A(f"| {label} | {unit} | " + " | ".join(n(v) for v in vals) + " |")

    A("\n### F.3.2 Installed capacity at the end of each period\n")
    A("| technology | units | 2030 | 2042 | 2055 |")
    A("|---|---|---|---|---|")
    for key, label, unit in TECHS:
        vals = [pb.get(p, {}).get("installed_capacities", {}).get(key) for p in PERIODS]
        A(f"| {label} | {unit} | " + " | ".join(n(v) for v in vals) + " |")
    A(
        "\nBuilding-integrated PV is offered to the optimiser in every period and is "
        "never built: it does not clear against rooftop PV on the same roof area.\n"
    )

    # ---------------------------------------------------------------- F.4
    A("\n---\n\n## F.4 Energy balance by period\n")
    A("All figures GWh per year unless stated.\n")
    A("| quantity | 2030 | 2042 | 2055 |")
    A("|---|---|---|---|")
    ebrows = [
        ("District demand", "annual_demand_kwh"),
        ("PV generation", "pv_generation_kwh"),
        ("Grid import", "grid_import_kwh"),
        ("Grid export", "grid_export_kwh"),
        ("Green open-access purchase", "green_purchase_kwh"),
        ("Data-centre contracted offtake", "dc_ppa_kwh"),
    ]
    for label, key in ebrows:
        A(f"| {label} | " + " | ".join(gwh(pb.get(p, {}).get(key)) for p in PERIODS) + " |")
    A(
        f"| Annual cost (INR crore) | "
        + " | ".join(cr(pb.get(p, {}).get("annual_cost_inr")) for p in PERIODS)
        + " |"
    )
    A(
        f"| Annual emissions (t CO2) | "
        + " | ".join(
            n((pb.get(p, {}).get("annual_emissions_kgco2") or 0) / 1000, 0) for p in PERIODS
        )
        + " |"
    )
    A(
        "\nEach period carries a weight in the objective equal to the years it "
        "represents: "
        + ", ".join(
            f"{p} = {n(pb.get(p, {}).get('represents_years'), 0)} years" for p in PERIODS
        )
        + ".\n"
    )

    # dispatchable generation is annual, reported on the production run
    A("\n### F.4.1 Dispatchable and flexible generation, production run\n")
    A("| source | GWh/yr |")
    A("|---|---|")
    for label, key in [
        ("Biomass CHP", "biomass_generation_kwh"),
        ("Waste to energy", "wte_generation_kwh"),
        ("Biogas", "biogas_generation_kwh"),
        ("Vehicle-to-grid discharge", "v2g_discharge_kwh"),
        ("Battery throughput", "battery_throughput_kwh"),
        ("Thermal storage throughput", "thermal_storage_throughput_kwh"),
        ("Demand response shifted", "dsr_shifted_kwh"),
        ("EV smart charging shifted", "ev_smart_shifted_kwh"),
        ("Solar thermal heat served", "solar_thermal_served_kwh"),
    ]:
        v = prod.get(key)
        if v is None:
            v = prod.get("capacities", {}).get(key)
        A(f"| {label} | {gwh(v)} |")
    A(
        "\nEvery dispatchable plant sits at its resource cap in every period, so the "
        "supply portfolio is resource-limited rather than economics-limited. The build "
        "trajectory is therefore not a free choice by the optimiser.\n"
    )

    # ---------------------------------------------------------------- F.5
    A("\n---\n\n## F.5 Boundary flows and procurement\n")
    A("| quantity | value |")
    A("|---|---|")
    for label, key, dp in [
        ("Grid connection sized (MW)", "grid_connection_mw", 2),
        ("Grid connection charge (INR/yr)", "grid_connection_cost_inr", 0),
        ("Green open-access purchase (kWh/yr)", "green_purchase_kwh", 0),
        ("Green open-access cost (INR/yr)", "green_purchase_cost_inr", 0),
        ("Data-centre offtake (kWh/yr)", "dc_ppa_offtake_kwh", 0),
        ("Data-centre revenue (INR/yr)", "dc_ppa_revenue_inr", 0),
        ("Data-centre contract volume (kWh/yr)", "dc_ppa_contract_kwh", 0),
        ("Data-centre coverage fraction", "dc_ppa_coverage_fraction", 4),
        ("Data-centre temporal match fraction", "dc_ppa_temporal_match_fraction", 4),
        ("Diesel backup required (kWh/yr)", "diesel_backup_kwh", 0),
    ]:
        A(f"| {label} | {n(prod.get(key), dp)} |")
    A(
        "\nDiesel backup is zero in every period. The town covers its own critical "
        "load, so it never buys the standby diesel the counterfactual needs.\n"
    )

    # The contract's net worth and carbon effect are established by an A/B solve,
    # not readable from a single run, so they are quoted from that artefact.
    A("\n### F.5.2 The data-centre contract raises emissions\n")
    A(
        "Established by an A/B solve, contract on against contract off. Source "
        "`outputs/verification/f5_recheck_20260821.txt`, 21 August 2026.\n"
    )
    A("| quantity | value |")
    A("|---|---|")
    A("| worth to the district | INR 284,029,440.73 /yr |")
    A("| offtake | 95,823,344.15 kWh |")
    A("| net concession tariff | INR 5.738220 /kWh |")
    A("| **emissions effect** | **+425,401.80 kg/yr** |")
    A(
        "\n**The contract is worth INR 284 M a year and it raises the town's "
        "emissions.** That is counter-intuitive for a renewable supply contract and "
        "the mechanism is worth stating precisely, because the obvious explanation is "
        "the wrong one.\n"
    )
    A(
        "It does **not** raise emissions by backfilling the offtake from grid import. "
        "Base-year import actually **falls** by 473,121 kWh with the contract on, and "
        "every dispatchable plant runs identically. The extra carbon is **embodied in "
        "a pulled-forward build**: the contract makes a larger farm worth building, "
        "241,462.2 kWp against 222,350.8 kWp without it, and a 2030-vintage module "
        "carries 810 kgCO2 per kWp.\n"
    )
    A(
        "The ledger closes exactly against the observed delta. Note the **1.10 "
        "end-of-life factor**: embodied carbon is charged at manufacture plus a 10 % "
        "end-of-life allowance, so the per-kWp rate that actually applies is "
        "810 x 1.10, not 810. Omitting it is why an unadjusted reading of this ledger "
        "appears not to balance.\n"
    )
    A("```")
    A("extra farm     +19,111.4 kWp x 810 x 1.10 / 25 yr  = +681,131.8")
    A("less rooftop      -397.1 kWp x 810 x 1.10 / 25 yr  =  -14,152.3")
    A("                                    embodied total = +666,979.5")
    A("less import    -473,121.4 kWh x 0.510604           = -241,577.7")
    A("SUM                                                 = +425,401.8  == observed")
    A("```\n")
    A(
        "This is the same cost-against-carbon tension that appears elsewhere in the "
        "results: a decision that is economically right and adds operational clean "
        "generation can still raise measured emissions once embodied carbon is counted "
        "per vintage. It is reported rather than netted away.\n"
    )

    inb = prod.get("internal_network_breakdown") or {}
    if inb.get("enabled"):
        A("\n### F.5.1 Internal distribution network\n")
        A("| component | annualised cost (INR/yr) |")
        A("|---|---|")
        for label, key in [
            ("Cables", "cable_annualised_inr"),
            ("Substation", "substation_annualised_inr"),
            ("Distribution transformers", "transformer_annualised_inr"),
        ]:
            A(f"| {label} | {n(inb.get(key), 0)} |")
        A(
            f"\nCable route {n(inb.get('cable_route_km'), 1)} km, substation "
            f"{n(inb.get('substation_mva_installed'), 0)} MVA installed. "
            "The same network is charged to both scenarios at parity, so it moves no "
            "build decision.\n"
        )
        emb = prod.get("internal_network_embodied") or {}
        if emb.get("enabled"):
            A(
                f"Embodied carbon of that network, annualised: "
                f"{n(emb.get('annualised_total_kgco2'), 0)} kgCO2/yr, also charged at "
                "parity.\n"
            )

    # ---------------------------------------------------------------- F.6
    if boundary:
        A("\n---\n\n## F.6 Boundary ledger by period\n")
        per = boundary.get("periods", {})
        keys = []
        for p in PERIODS:
            for k in (per.get(p) or {}):
                if k not in keys:
                    keys.append(k)
        if keys:
            A("| quantity | 2030 | 2042 | 2055 |")
            A("|---|---|---|---|")
            for k in keys:
                vals = [(per.get(p) or {}).get(k) for p in PERIODS]
                if all(isinstance(v, (int, float)) or v is None for v in vals):
                    A(f"| `{k}` | " + " | ".join(n(v, 2) for v in vals) + " |")

    # ---------------------------------------------------------------- F.7
    A("\n---\n\n## F.7 Cost and carbon frontier\n")
    A(
        "The carbon weight alpha trades annualised cost against emissions. Alpha 0 is "
        "the production case.\n"
    )
    A("| alpha | annual cost (INR) | annual CO2 (kg) | cost vs alpha 0 | CO2 vs alpha 0 |")
    A("|---|---|---|---|---|")
    base = sweep[0][1] if sweep else prod
    for a, s in sweep:
        dc = (s["annual_cost_inr"] / base["annual_cost_inr"] - 1) * 100
        de = (s["annual_emissions_kgco2"] / base["annual_emissions_kgco2"] - 1) * 100
        A(
            f"| {a:g} | {n(s['annual_cost_inr'], 0)} | {n(s['annual_emissions_kgco2'], 0)} | "
            f"{dc:+.2f} % | {de:+.2f} % |"
        )
    A(
        "\nRead this in horizon terms rather than base-year annual terms. In base-year "
        "annual terms the frontier looks flat over much of its range and is not "
        "monotone, because the objective trades across three weighted periods while the "
        "annual figure reports only one.\n"
    )

    # ---------------------------------------------------------------- F.8
    if equity:
        A("\n---\n\n## F.8 Bills and savings by consumer class\n")
        by = equity.get("by_class", {})
        A("| class | BAU bill (INR/yr) | district bill (INR/yr) | saving |")
        A("|---|---|---|---|")
        for cls, v in by.items():
            b = v.get("bau_bill_inr") or v.get("total_bau_bill_inr")
            t = v.get("district_bill_inr") or v.get("total_district_bill_inr")
            if b and t:
                A(f"| {cls.replace('_', ' ')} | {n(b, 0)} | {n(t, 0)} | {(1 - t / b) * 100:.1f} % |")
        tot = equity.get("totals", {})
        tb, td = tot.get("total_bau_bill_inr"), tot.get("total_district_bill_inr")
        if tb and td:
            A(f"| **all classes** | {n(tb, 0)} | {n(td, 0)} | {(1 - td / tb) * 100:.1f} % |")
        p2p = equity.get("p2p", {})
        if p2p:
            A(
                f"\nPeer-to-peer trading moves {n(p2p.get('annual_volume_kwh'), 0)} kWh/yr, "
                f"{n(p2p.get('volume_pct_of_demand'), 2)} % of demand, redistributing "
                f"{n(p2p.get('annual_welfare_redistributed_inr'), 0)} INR/yr at a traded "
                f"price of {n(p2p.get('p2p_price_inr_per_kwh'), 2)} INR/kWh. "
                "It is a settlement layer rather than an optimiser decision: the single "
                "bus already pools surplus generation, so trading redistributes money "
                "without moving a kilowatt-hour. Its welfare effect is an order of "
                "magnitude below what central generation and the ownership structure "
                "deliver.\n"
            )

    # ---------------------------------------------------------------- F.9
    if techfin:
        A("\n---\n\n## F.9 Per-technology economics\n")
        techs = techfin.get("technologies", [])
        if techs:
            cols = [c for c in ("name", "capex_inr", "annualised_inr", "annual_value_inr",
                                "lcoe_inr_per_kwh", "irr_pct", "payback_years") if any(c in t for t in techs)]
            A("| " + " | ".join(c.replace("_", " ") for c in cols) + " |")
            A("|" + "---|" * len(cols))
            for t in techs:
                cells = []
                for c in cols:
                    v = t.get(c)
                    cells.append(v if isinstance(v, str) else n(v, 2) if isinstance(v, (int, float)) else "-")
                A("| " + " | ".join(str(x) for x in cells) + " |")
        A(
            "\nAttribution convention: "
            f"{techfin.get('meta', {}).get('attribution', 'see the report file')}\n"
        )

    A(
        "\n---\n\n**Source files.** `outputs/data/energy/dispatch_results.json`, "
        "`equity_report.json`, `owner_finance.json`, `tech_finance_report.json`, "
        "`boundary_flows_ledger.json`.\n"
    )

    out_path = os.path.abspath(os.path.join(root, OUT))
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    text = "\n".join(P).replace("—", " - ")
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(text + "\n")
    print(f"wrote {out_path}")
    print(f"  cost saving {cs:.4f} %, emissions saving {es:.4f} %")
    print(f"  {len(sweep)} points on the carbon frontier")


if __name__ == "__main__":
    main()
